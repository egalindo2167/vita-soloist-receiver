#!/usr/bin/env python3
"""Regenerate the shipped Vita UI bitmap font from pinned DejaVu Sans 2.37.

Only needed when changing typography; no font or Python dependency is required
to compile/use the Vita release. See UI-FONT-LICENSE.txt for redistribution.
"""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

PINS = {
    'DejaVuSans.ttf': 'ae7b7855e115a5966d8b1b3f80f254ccc117ec86f9965e202ee2940453837280',
    'DejaVuSans-Bold.ttf': '5c1247acef7f2b8522a31742c76d6adcb5569bacc0be7ceaa4dc39dd252ce895',
}
SIZES = [(14,False),(16,False),(18,False),(26,True),(30,True)]
CHARS = list(range(32,256))+[0x2013,0x2014,0x2018,0x2019,0x201c,0x201d,0x2022,0x2026,0x266a]

def build(font_dir,root):
    for name,digest in PINS.items():
        if hashlib.sha256((font_dir/name).read_bytes()).hexdigest()!=digest:
            raise SystemExit(f'Font hash mismatch: {name}')
    glyphs=[]; pixels=bytearray()
    for size,bold in SIZES:
        font=ImageFont.truetype(str(font_dir/('DejaVuSans-Bold.ttf' if bold else 'DejaVuSans.ttf')),size,
                                layout_engine=ImageFont.Layout.BASIC)
        for code in CHARS:
            c=chr(code);left,top,right,bottom=font.getbbox(c)
            w,h=right-left,bottom-top
            mask=Image.new('L',(max(1,w),max(1,h)))
            if w and h: ImageDraw.Draw(mask).text((-left,-top),c,font=font,fill=255)
            glyphs.append((len(pixels),left,top,w,h,round(font.getlength(c))))
            if w and h:pixels.extend(mask.tobytes())
    header='''/* Generated by tools/build_ui_font.py from DejaVu Sans 2.37.
 * Copyright (c) 2003 Bitstream, Inc. DejaVu changes public domain.
 * See UI-FONT-LICENSE.txt. Raster asset name: Vita UI Sans. */
#ifndef RECEIVER_UI_FONT_DATA_H
#define RECEIVER_UI_FONT_DATA_H
#include <stdint.h>
typedef struct { uint32_t offset; int16_t left,top; uint16_t width,height,advance; } UiFontGlyph;
extern const UiFontGlyph ui_font_glyphs[1165];
extern const uint8_t ui_font_pixels[];
extern const uint32_t ui_font_extra[9];
#define UI_FONT_GLYPHS 233
#endif
'''
    assert len(glyphs)==1165
    (root/'src/ui_font_data.h').write_text(header)
    lines=['/* Generated; see ui_font_data.h and UI-FONT-LICENSE.txt. */','#include "ui_font_data.h"',
           'const uint32_t ui_font_extra[9]={'+','.join(hex(x) for x in CHARS[224:])+'};',
           'const UiFontGlyph ui_font_glyphs[1165]={']
    lines.extend('{'+','.join(map(str,g))+'},' for g in glyphs)
    lines.extend(['};','const uint8_t ui_font_pixels[]={'])
    for at in range(0,len(pixels),32):lines.append(','.join(str(x) for x in pixels[at:at+32])+',')
    lines.append('};\n');(root/'src/ui_font_data.c').write_text('\n'.join(lines))
    print(f'Generated {len(glyphs)} glyphs, {len(pixels)} alpha bytes.')

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font-dir',type=Path,default=Path('/usr/share/fonts/truetype/dejavu'))
    args=parser.parse_args();build(args.font_dir,Path(__file__).resolve().parents[1])
