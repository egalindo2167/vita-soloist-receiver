#ifndef RECEIVER_AUDIO_POLICY_H
#define RECEIVER_AUDIO_POLICY_H
#include "protocol.h"
#define AUDIO_CAPACITY_BLOCKS 96u
#define AUDIO_CAPACITY_BYTES (VPCM_BLOCK_BYTES*AUDIO_CAPACITY_BLOCKS)
#define AUDIO_CAPACITY_MS (AUDIO_CAPACITY_BYTES*1000u/(VPCM_RATE*4u))
#define AUDIO_LOCAL_START_BLOCKS 12u
#define AUDIO_REMOTE_START_BLOCKS 48u
static inline unsigned audio_start_bytes(int remote) {
    return VPCM_BLOCK_BYTES*(remote?AUDIO_REMOTE_START_BLOCKS:AUDIO_LOCAL_START_BLOCKS);
}
#endif
